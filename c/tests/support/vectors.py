#!/usr/bin/env python3
"""Writes the specification's test vectors as a C header, for the C tests:

    python3 vectors.py --spec SPEC --out vectors.h

spec/vectors/signatures.json (signed requests, § 5.4), spki.json (the
server's key, § 5.3) and paths.json (§ 8.2) become arrays of structs, every
string a C literal. Standard library only.
"""
import argparse
import json
from pathlib import Path


def c_string(value):
    """A C string literal: printable ASCII as is, every other byte in octal."""
    out = ['"']
    for byte in value.encode("utf-8"):
        char = chr(byte)
        if char in '"\\':
            out.append("\\" + char)
        elif 0x20 <= byte < 0x7F and char != "?":
            out.append(char)
        else:
            out.append(f"\\{byte:03o}")
    out.append('"')
    return "".join(out)


def request_fields(request):
    headers = request.get("headers", {})
    return ", ".join([
        c_string(request.get("name", "")),
        c_string(request["method"]),
        c_string(request["uri"]),
        c_string(request.get("body", "")),
        c_string(headers.get("Authorization", "")),
        c_string(headers.get("Content-Digest", "")),
        c_string(headers.get("Signature-Input", "")),
        c_string(headers.get("Signature", "")),
        c_string(request.get("signature_base", "")),
    ])


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--spec", required=True)
    p.add_argument("--out", required=True)
    args = p.parse_args()
    vectors = Path(args.spec) / "vectors"
    signatures = json.loads((vectors / "signatures.json").read_text(encoding="utf-8"))
    spki = json.loads((vectors / "spki.json").read_text(encoding="utf-8"))
    paths = json.loads((vectors / "paths.json").read_text(encoding="utf-8"))

    lines = [
        "/* Generated by c/tests/support/vectors.py from spec/vectors: do not edit. */",
        "#ifndef LANTERN_TEST_VECTORS_H",
        "#define LANTERN_TEST_VECTORS_H",
        "",
        "#include <stdbool.h>",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "typedef struct signed_request",
        "{",
        "    const char* name;",
        "    const char* method;",
        "    const char* uri;",
        "    const char* body;",
        "    const char* authorization;",
        "    const char* content_digest;",
        "    const char* signature_input;",
        "    const char* signature;",
        "    const char* signature_base;",
        "} signed_request;",
        "",
        "typedef struct refused_request",
        "{",
        "    const char* name;",
        "    signed_request request;",
        "    const char* code;",
        "    const char* after; /* an accepted request's name sent first, or \"\" */",
        "} refused_request;",
        "",
        f"static const char* const vector_seed = {c_string(signatures['key']['seed'])};",
        f"static const char* const vector_keyid = {c_string(signatures['key']['keyid'])};",
        f"static const char* const vector_fingerprint = {c_string(signatures['key']['short_fingerprint'])};",
        f"static const int64_t vector_server_time = {int(signatures['server_time'])};",
        f"static const uint32_t vector_skew = {int(signatures['skew'])}U;",
        "",
        "static const signed_request accepted_requests[] = {",
    ]
    for request in signatures["accepted"]:
        lines.append(f"    {{ {request_fields(request)} }},")
    lines.append("};")
    lines.append("")
    lines.append("static const refused_request refused_requests[] = {")
    for refused in signatures["refused"]:
        after = refused.get("after", [])
        lines.append(f"    {{ {c_string(refused['name'])}, {{ {request_fields(refused['request'])} }}, "
                     f"{c_string(refused['code'])}, {c_string(after[0] if after else '')} }},")
    lines.append("};")
    lines.append("")
    lines.append("typedef struct spki_vector")
    lines.append("{")
    lines.append("    const char* name;")
    lines.append("    const char* pem;")
    lines.append("    const char* spki_sha256;")
    lines.append("    const char* short_form;")
    lines.append("} spki_vector;")
    lines.append("")
    lines.append("static const spki_vector spki_vectors[] = {")
    for cert in spki["certificates"]:
        lines.append(f"    {{ {c_string(cert['name'])}, {c_string(cert['pem'])}, {c_string(cert['spki_sha256'])}, "
                     f"{c_string(cert['short'])} }},")
    lines.append("};")
    lines.append("")
    lines.append("typedef struct path_vector")
    lines.append("{")
    lines.append("    const char* path;")
    lines.append("    size_t size; /* a path may hold a NUL */")
    lines.append("    bool accepted;")
    lines.append("    const char* why;")
    lines.append("} path_vector;")
    lines.append("")
    lines.append("static const path_vector path_vectors[] = {")
    for path in paths["paths"]:
        lines.append(f"    {{ {c_string(path['path'])}, {len(path['path'].encode('utf-8'))}U, "
                     f"{'true' if path['accepted'] else 'false'}, "
                     f"{c_string(path['why'])} }},")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
