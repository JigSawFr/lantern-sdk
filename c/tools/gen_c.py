#!/usr/bin/env python3
"""Generates the C API's documents: opaque types and accessor functions over
the C++ library's generated structs, and their readers.

    python3 c/tools/gen_c.py           # writes the files
    python3 c/tools/gen_c.py --check   # fails when they are stale

It runs cpp/tools/gen_types.py's own model of spec/schemas/v1 (imported,
not copied), so that each C accessor reads the very member the C++ binder
fills, and writes:

- c/include/lantern/lantern_documents.h: `typedef struct lantern_app
  lantern_app;` for every type a document read holds, and one function per
  member: lantern_app_get_name(app);
- c/src/generated/documents.hpp: the casts between those opaque types and
  the C++ structs, for the hand-written sources;
- c/src/generated/documents.cpp: the accessors, each document's reader
  (lantern_read_apps_page) and its free function.

How a member is read (c/README.md says why accessors rather than structs):
- a string (a nullable one, a raw JSON value too): lantern_str, empty when
  absent, borrowed from the document;
- an integer, a boolean, a SHA-256: `bool get(const T*, X* out)`, false
  when the member is absent, so that a member a later schema makes
  optional keeps its signature;
- an object: `const lantern_x*`, NULL when absent;
- an array: `_count()` and `_at(index)` (out of range: empty, false or
  NULL); an array of arrays has `_size(i)` and `_at(i, j)`;
- members kept raw (`extra`, requires.min): `_count()` and `_at(index,
  &key, &json)`.

Standard library only.
"""
import argparse
import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
C = HERE.parent
ROOT = C.parent
HEADER = C / "include" / "lantern" / "lantern_documents.h"
CASTS = C / "src" / "generated" / "documents.hpp"
SOURCE = C / "src" / "generated" / "documents.cpp"
HAND_HEADER = C / "include" / "lantern" / "lantern.h"


def load_cpp_generator():
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location("lantern_gen_types", ROOT / "cpp" / "tools" / "gen_types.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# The sync values (gen_types.py's VALUES) given accessors here.
C_VALUES = {"Wish"}


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def c_type(name):
    return f"lantern_{snake(name)}"


def draft():
    """The specification's draft, as cpp/tools/gen_types.py's banner names it."""
    return re.search(r"\(draft ([0-9.]+)\)", load_cpp_generator().BANNER).group(1)


BANNER_C = """/*
 * Generated by c/tools/gen_c.py from cpp/tools/gen_types.py's model of
 * spec/schemas/v1 (draft {draft}). Do not edit: change the generator, then
 * run it again.
 */"""

BANNER_CPP = """// Generated by c/tools/gen_c.py from cpp/tools/gen_types.py's model of
// spec/schemas/v1 (draft {draft}). Do not edit: change the generator, then
// run it again."""


class Model:
    def __init__(self):
        gt = load_cpp_generator()
        self.gt = gt
        schemas = gt.Schemas(gt.SCHEMAS)
        g = gt.Generator(schemas)
        self.documents = []  # (file, C++ reader, C++ type)
        for file, function, type_name, direction in gt.DOCUMENTS:
            schema = schemas.files[file]
            named = g.ref_name(schema, file)
            if named:
                target, _, _ = schemas.resolve_ref(f"common.json#/$defs/{named}", file)
                name = g.object_type(target, "common.json", gt.NAMED[named])
            else:
                name = g.object_type(schema, file, type_name)
            if direction == "read":
                self.documents.append((file, function, name))
        # The values of a sync item the C API reads through accessors (the
        # C++ library's read_wish); `installed` is read by hand (lantern.h),
        # its parts having the names of lantern.h's input structs
        self.values = []
        for named in getattr(gt, "VALUES", []):
            target, _, _ = schemas.resolve_ref(f"common.json#/$defs/{named}", "common.json")
            name = g.object_type(target, "common.json", gt.NAMED[named])
            if name in C_VALUES:
                self.values.append(name)
        self.types = g.types
        # The types a read document holds, in the C++ order (nested first)
        reachable = []

        def visit(name):
            if name in reachable:
                return
            for f in self.types[name].fields:
                for nested in gt.nested_types(f):
                    visit(nested)
            reachable.append(name)

        for _, _, name in self.documents:
            visit(name)
        for name in self.values:
            visit(name)
        order = gt.ordered(g)
        self.order = [name for name in order if name in reachable]
        self.roots = []
        for _, _, name in [*self.documents, *((None, None, v) for v in self.values)]:
            if name not in self.roots:
                self.roots.append(name)


def members(model, t):
    fields = list(t.fields)
    if t.extra:
        fields.append(model.gt.Field("extra", "members", False))
    return fields


SCALARS = {
    "u64": ("uint64_t", "std::uint64_t"),
    "i64": ("int64_t", "std::int64_t"),
    "bool": ("bool", "bool"),
}


def declarations(model, t):
    """(C declaration, C++ body) of each accessor of `t`."""
    out = []
    tn = c_type(t.name)
    arg = f"const {tn}* value"
    for f in members(model, t):
        base = f"{tn}_get_{f.json_name}"
        member = f"v->{f.name}"
        kind = f.kind
        if kind in ("string", "nullable", "raw"):
            out.append((f"lantern_str {base}({arg})",
                        f"const auto* v = as(value);\n    return v ? view({member}) : empty_str();"))
        elif kind == "digest":
            if f.required:
                body = f"const auto* v = as(value);\n    if (v == nullptr || out == nullptr)\n        return false;\n    copy_digest({member}, out);\n    return true;"
            else:
                body = f"const auto* v = as(value);\n    if (v == nullptr || out == nullptr || !{member})\n        return false;\n    copy_digest(*{member}, out);\n    return true;"
            out.append((f"bool {base}({arg}, uint8_t out[32])", body))
        elif kind in SCALARS:
            ctype, _ = SCALARS[kind]
            if f.required:
                body = f"const auto* v = as(value);\n    if (v == nullptr || out == nullptr)\n        return false;\n    *out = {member};\n    return true;"
            else:
                body = f"const auto* v = as(value);\n    if (v == nullptr || out == nullptr || !{member})\n        return false;\n    *out = *{member};\n    return true;"
            out.append((f"bool {base}({arg}, {ctype}* out)", body))
        elif kind == "object":
            sub = f.info["type"]
            if f.required:
                body = f"const auto* v = as(value);\n    return v ? wrap(&{member}) : nullptr;"
            else:
                body = f"const auto* v = as(value);\n    return v && {member} ? wrap(&*{member}) : nullptr;"
            out.append((f"const {c_type(sub)}* {base}({arg})", body))
        elif kind == "members":
            out.append((f"size_t {base}_count({arg})",
                        f"const auto* v = as(value);\n    return v ? {member}.size() : 0;"))
            out.append((f"bool {base}_at({arg}, size_t index, lantern_str* key, lantern_str* json)",
                        f"const auto* v = as(value);\n    if (v == nullptr || index >= {member}.size())\n        return false;\n"
                        f"    if (key != nullptr)\n        *key = view({member}[index].first);\n"
                        f"    if (json != nullptr)\n        *json = view({member}[index].second);\n    return true;"))
        elif kind == "array":
            element = f.info["element"]
            out.append((f"size_t {base}_count({arg})",
                        f"const auto* v = as(value);\n    return v ? {member}.size() : 0;"))
            ek = element.kind
            guard = f"const auto* v = as(value);\n    if (v == nullptr || index >= {member}.size())"
            if ek in ("string", "nullable", "raw"):
                out.append((f"lantern_str {base}_at({arg}, size_t index)",
                            f"{guard}\n        return empty_str();\n    return view({member}[index]);"))
            elif ek == "digest":
                out.append((f"bool {base}_at({arg}, size_t index, uint8_t out[32])",
                            f"{guard}\n        return false;\n    if (out == nullptr)\n        return false;\n    copy_digest({member}[index], out);\n    return true;"))
            elif ek in SCALARS:
                ctype, _ = SCALARS[ek]
                out.append((f"bool {base}_at({arg}, size_t index, {ctype}* out)",
                            f"{guard}\n        return false;\n    if (out == nullptr)\n        return false;\n    *out = {member}[index];\n    return true;"))
            elif ek == "object":
                sub = element.info["type"]
                out.append((f"const {c_type(sub)}* {base}_at({arg}, size_t index)",
                            f"{guard}\n        return nullptr;\n    return wrap(&{member}[index]);"))
            elif ek == "array" and element.info["element"].kind == "object":
                sub = element.info["element"].info["type"]
                out.append((f"size_t {base}_size({arg}, size_t index)",
                            f"{guard}\n        return 0;\n    return {member}[index].size();"))
                out.append((f"const {c_type(sub)}* {base}_at({arg}, size_t index, size_t item)",
                            f"{guard}\n        return nullptr;\n    if (item >= {member}[index].size())\n        return nullptr;\n"
                            f"    return wrap(&{member}[index][item]);"))
            else:
                raise ValueError(f"{t.name}.{f.json_name}: an array of {ek}")
        else:
            raise ValueError(f"{t.name}.{f.json_name}: {kind}")
    return out


def reader_name(function):
    return "lantern_" + function


def generate():
    model = Model()
    banner_c, banner_cpp = BANNER_C.format(draft=draft()), BANNER_CPP.format(draft=draft())
    header = [banner_c, "#ifndef LANTERN_LANTERN_DOCUMENTS_H", "#define LANTERN_LANTERN_DOCUMENTS_H", "",
              "#ifndef LANTERN_LANTERN_H", '#error "include <lantern/lantern.h>, which includes this file"', "#endif",
              "", "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
              "/* The `schema` of the documents this library reads (SPEC.md § 3.2). */",
              f"#define LANTERN_KNOWN_SCHEMA {1}", "",
              "/* Every type a document holds: opaque, read through the functions below. */"]
    for name in model.order:
        header.append(f"typedef struct {c_type(name)} {c_type(name)};")
    header.append("")
    symbols = []
    source_parts = []
    for name in model.order:
        t = model.types[name]
        header.append(f"/* {name}" + (f": {t.description}." if t.description else ".") + " */")
        for declaration, body in declarations(model, t):
            header.append(f"LANTERN_API {declaration};")
            symbols.append(declaration)
            source_parts.append(f"LANTERN_API {declaration}\n{{\n    {body}\n}}")
        header.append("")
    header.append("/* The documents, read with the `schema` rule: LANTERN_ABSENT and *out NULL for a")
    header.append(" * document of a newer schema, an error for one without `schema`; unknown members")
    header.append(" * are skipped. The text need not be NUL-terminated. Each document is freed with")
    header.append(" * its free function; what its accessors give lives as long as it does. */")
    for file, function, name in model.documents:
        tn = c_type(name)
        header.append(f"/* {file} */")
        decl = (f"lantern_status {reader_name(function)}(const char* text, size_t size, const lantern_limits* limits,\n"
                f"    const lantern_allocator* allocator, {tn}** out, lantern_error* error)")
        header.append(f"LANTERN_API {decl};")
        source_parts.append(
            f"LANTERN_API {decl}\n{{\n"
            f"    return read_text<lantern::{name}>(text, size, limits, allocator, out, error,\n"
            f"        [](std::string_view input, const lantern::DecodeOptions& options) {{ return lantern::{function}(input, options); }});\n}}")
    header.append("")
    header.append("/* Frees a document a function gave (never one borrowed from another). */")
    for name in model.roots:
        tn = c_type(name)
        decl = f"void {tn}_free({tn}* value)"
        header.append(f"LANTERN_API {decl};")
        source_parts.append(f"LANTERN_API {decl}\n{{\n    unbox(as_mutable(value));\n}}")
    header += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif /* LANTERN_LANTERN_DOCUMENTS_H */", ""]

    casts = [banner_cpp, "#pragma once", "", "#include <lantern/lantern.h>", "", "#include <lantern/types.hpp>",
             "", "// The opaque types of the C API are the C++ structs, seen through a pointer.",
             "namespace lantern_c", "{", ""]
    for name in model.order:
        tn = c_type(name)
        casts.append(f"inline const lantern::{name}* as(const {tn}* value) noexcept")
        casts.append("{")
        casts.append(f"    return reinterpret_cast<const lantern::{name}*>(value);")
        casts.append("}")
        casts.append(f"inline lantern::{name}* as_mutable({tn}* value) noexcept")
        casts.append("{")
        casts.append(f"    return reinterpret_cast<lantern::{name}*>(value);")
        casts.append("}")
        casts.append(f"inline const {tn}* wrap(const lantern::{name}* value) noexcept")
        casts.append("{")
        casts.append(f"    return reinterpret_cast<const {tn}*>(value);")
        casts.append("}")
        casts.append(f"inline {tn}* wrap_mutable(lantern::{name}* value) noexcept")
        casts.append("{")
        casts.append(f"    return reinterpret_cast<{tn}*>(value);")
        casts.append("}")
        casts.append("")
    casts += ["} // namespace lantern_c", ""]

    source = [banner_cpp, '#include "generated/documents.hpp"', "", "#include <cstddef>", "#include <cstdint>",
              "#include <string_view>", "", '#include "internal.hpp"', "", "using namespace lantern_c;", "",
              "// NOLINTBEGIN(readability-identifier-naming,misc-use-internal-linkage)", 'extern "C" {', ""]
    for part in source_parts:
        source.append(part)
        source.append("")
    source += ["} // extern \"C\"", "// NOLINTEND(readability-identifier-naming,misc-use-internal-linkage)", ""]

    check_names(model, symbols)
    return "\n".join(header), "\n".join(casts), "\n".join(source)


def check_names(model, symbols):
    """No generated name is one of lantern.h's, or twice the same."""
    hand = set(re.findall(r"\blantern_[a-z0-9_]+\b", HAND_HEADER.read_text(encoding="utf-8")))
    generated = [re.search(r"(lantern_[a-z0-9_]+)\(", s).group(1) for s in symbols]
    generated += [c_type(n) for n in model.order]
    seen = set()
    for name in generated:
        if name in seen:
            raise SystemExit(f"gen_c.py: {name} is generated twice")
        seen.add(name)
    # lantern.h names the documents it returns; that is not a clash
    clashes = sorted((seen & hand) - {c_type(n) for n in model.order})
    if clashes:
        raise SystemExit("gen_c.py: generated names that lantern.h has too: " + ", ".join(clashes))


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--check", action="store_true", help="fail when the committed files differ")
    args = p.parse_args(argv)
    header, casts, source = generate()
    outputs = ((HEADER, header), (CASTS, casts), (SOURCE, source))
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, text in outputs
                 if not path.exists() or path.read_text(encoding="utf-8") != text]
        if stale:
            print("stale, run python3 c/tools/gen_c.py: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("generated C documents: up to date")
        return 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print("wrote " + ", ".join(str(path.relative_to(ROOT)) for path, _ in outputs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
